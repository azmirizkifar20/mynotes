const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { randomUUID } = require('node:crypto');
assert.equal(process.env.MDPREVIEW_TEST_ISOLATED, '1');
assert.equal(process.env.DB_HOST, '127.0.0.1');
assert.equal(process.env.DB_USER, 'fixture');
assert.equal(process.env.DB_NAME, 'postgres');
assert(!fs.existsSync(path.join(__dirname, '../.env')), 'Never use the shared database');
const db = require('../src/backend/database');
const tasks = require('../src/backend/modules/task-board/service');
const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'pdf-check-'));
require('../src/backend/config/paths').docs = temporary;
const { documentData } = require('../src/backend/modules/documents/markdown');
const pdf = require('./helpers/pdf.cjs');
const status = code => error => error.status === code;
let server;
async function main() {
  await db.initialize();
  await db.query("ALTER TABLE mdpreview.entries DROP CONSTRAINT entries_kind_check; ALTER TABLE mdpreview.entries ADD CONSTRAINT entries_kind_check CHECK(kind IN ('doc','folder','asset'))");
  const root = randomUUID();
  await db.query("INSERT INTO mdpreview.entries(id,path,kind) VALUES($1,'/','folder')", [root]);
  const markdown = await db.save('/keep.md', '# unchanged', { create: true });
  await db.initialize(); await db.initialize();
  assert.deepEqual((await db.get('/keep.md')).content, markdown.content, 'Migration preserves existing bytes');
  await db.createFolder('/files'); await db.createFolder('/other');
  let row = await db.savePdf('/files/brief.pdf', pdf);
  assert.equal(row.kind, 'pdf'); assert.equal(row.visibility, 'private');
  assert.deepEqual(row.content, pdf);
  await assert.rejects(db.savePdf('/files/brief.pdf', pdf), status(409));
  for (const [name, bytes] of [['/bad.pdf', Buffer.from('not PDF')], ['/bad.md', pdf], ['/../bad.pdf', pdf], ['/bad.pdf', Buffer.from('%PDF-1.7\nno EOF')], ['/bad.pdf', Buffer.alloc(5*1024*1024+1)]])
    await assert.rejects(db.savePdf(name, bytes), status(400));
  await assert.rejects(db.save('/files/brief.pdf', '# overwrite'), status(400));
  assert((await db.workspace()).some(page => page.id === row.id && page.type === 'pdf'));
  const metadata = documentData(row, '/mynotes');
  assert.equal(metadata.type, 'pdf'); assert(!metadata.content && !metadata.html);
  assert.equal(metadata.pdfUrl, '/mynotes/media?document=%2Ffiles%2Fbrief.pdf');
  assert((await tasks.suggestDocuments('brief.pdf')).some(item => item.id === row.id));
  let board = await tasks.list();
  const mention = `@[brief.pdf](doc:${row.id})`;
  let saved = await tasks.saveTask({ title: 'Read PDF', description: mention, result: mention, statusId: board.statuses.find(s => s.completed).id, priority: 'normal', due: '', revision: board.revision });
  assert(saved.board.documents.some(item => item.id === row.id));
  await db.move('/files/brief.pdf', '/other/Ringkasan.pdf');
  assert.equal(await tasks.mentionedDocument(row.id), '/other/Ringkasan.pdf');
  assert.deepEqual((await db.get('/other/Ringkasan.pdf')).content, pdf);
  let impact;
  try { await db.trash('/other', true); } catch (error) { assert.equal(error.status, 409); impact = error.mentionImpact; }
  assert.equal(impact.taskCount, 1); assert.equal(impact.documentCount, 1);
  await db.trash('/other', true, undefined, impact.token);
  await assert.rejects(tasks.mentionedDocument(row.id), status(404));
  const trashed = (await db.query('SELECT trash_id FROM mdpreview.entries WHERE id=$1', [row.id])).rows[0];
  await db.restoreTrash(trashed.trash_id, false);
  assert.equal(await tasks.mentionedDocument(row.id), '/other/Ringkasan.pdf');
  require('../src/backend/modules/documents/mirror').sync = async () => {};
  const express = require('express'), app = express(), router = express.Router(), api = express.Router();
  app.set('views', path.join(__dirname, '../src/frontend/views')); app.set('view engine', 'ejs');
  Object.assign(app.locals, { assetVersion: 'fixture', editorVersion: '4.0.1', passkeyBrowserVersion: '14.0.0' });
  app.use('/mynotes', router); app.use(router); router.use(express.json());
  router.use((req, res, next) => { res.locals.basePath = req.baseUrl; req.session = { authenticated: req.get('X-Fixture-Auth') === '1' }; next(); });
  router.use('/api', require('../src/backend/middleware/origin'));
  api.use(require('../src/backend/middleware/require-auth'));
  const upload = require('multer')({ dest: temporary, limits: { fileSize: 5*1024*1024, files: 1 } });
  const context = { documentData, upload };
  for (const feature of ['documents/routes', 'documents/history', 'documents/drafts', 'workspace/routes', 'task-board/routes']) require('../src/backend/modules/' + feature)(api, context);
  router.use('/api', api); router.use(require('../src/backend/modules/documents/public-routes'));
  router.use(require('../src/backend/middleware/error-handler'));
  server = app.listen(0, '127.0.0.1'); await new Promise(resolve => server.once('listening', resolve));
  const url = 'http://127.0.0.1:' + server.address().port;
  for (const prefix of ['', '/mynotes']) {
    const base = url + prefix, headers = { 'X-Fixture-Auth': '1', 'Content-Type': 'application/json' };
    const post = (route, body, extra = {}) => fetch(base + '/api/' + route, { method: 'POST', headers: { ...headers, ...extra }, body: JSON.stringify(body) });
    const filePath = '/other/Ringkasan.pdf', media = base + '/media?document=' + encodeURIComponent(filePath);
    assert.equal((await fetch(media)).status, 404, 'Guest cannot fetch private bytes');
    const privatePage = await (await fetch(base + filePath)).text(); assert(privatePage.includes('"mode":"login"'));
    const data = await (await post('document', { filePath })).json(); assert.equal(data.type, 'pdf'); assert.equal(data.pdfUrl, prefix + '/media?document=' + encodeURIComponent(filePath));
    assert.equal((await post('raw', { filePath })).status, 400, 'PDF cannot be decoded by Markdown editor');
    const bytes = await fetch(media, { headers });
    assert.equal(bytes.status, 200); assert.equal(bytes.headers.get('content-type'), 'application/pdf');
    assert.equal(bytes.headers.get('cache-control'), 'no-store'); assert.equal(bytes.headers.get('x-content-type-options'), 'nosniff');
    assert(bytes.headers.get('content-disposition').startsWith('inline;')); assert.deepEqual(Buffer.from(await bytes.arrayBuffer()), pdf);
    assert((await fetch(media + '&download=1', { headers })).headers.get('content-disposition').startsWith('attachment;'));
    assert((await (await fetch(base + '/api/search?q=Ringkasan', { headers })).json()).items.some(item => item.id === row.id));
    const open = await fetch(base + '/api/task-board/documents/' + row.id + '/open', { headers, redirect: 'manual' });
    assert.equal(open.status, 302); assert.equal(open.headers.get('location'), prefix + filePath);
    const shared = await post('share', { filePath, visibility: 'public' }); assert.equal(shared.status, 200);
    assert.equal((await fetch(media)).status, 200);
    assert((await (await fetch(base + filePath)).text()).includes('"type":"pdf"'));
    const shareId = (await db.get(filePath)).share_id;
    assert.equal((await fetch(base + '/share/' + shareId)).status, 200);
    await post('share', { filePath, visibility: 'private' }); assert.equal((await fetch(media)).status, 404);
    assert.equal((await post('share', { filePath, visibility: 'public' }, { Origin: 'https://evil.invalid' })).status, 403);
    const uploadFile = async (filename, content = pdf, original = 'source.pdf', auth = true) => {
      const form = new FormData(); form.append('targetFolder', '/files'); form.append('filename', filename); form.append('file', new Blob([content], { type: 'application/pdf' }), original);
      return fetch(base + '/api/upload', { method: 'POST', headers: auth ? { 'X-Fixture-Auth': '1' } : {}, body: form });
    };
    const name = prefix ? 'mount.pdf' : 'root.pdf';
    assert.equal((await uploadFile(name)).status, 200); assert.deepEqual((await db.get('/files/' + name)).content, pdf);
    assert.equal((await uploadFile(name)).status, 409, 'Duplicate never overwrites');
    assert.equal((await uploadFile('wrong.md')).status, 400);
    assert.equal((await uploadFile('invalid.pdf', Buffer.from('invalid'))).status, 400);
    assert.equal((await uploadFile('large.pdf', Buffer.alloc(5*1024*1024+1))).status, 400);
    assert.equal((await uploadFile('unauthorized.pdf', pdf, 'source.pdf', false)).status, 401);
    assert.equal(fs.readdirSync(temporary).length, 0, 'Temporary uploads cleaned after success and failure');
  }
  await db.query('DELETE FROM mdpreview.entries');
  await db.query('DELETE FROM mdpreview.tasks');
  console.log('PDF migration, binary persistence, validation, private/public access, both mounts, upload cleanup, stable task mentions and deletion guard passed.');
}
main().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => { server?.closeAllConnections(); if (server) await new Promise(resolve => server.close(resolve)); await db.pool.end(); fs.rmSync(temporary, { recursive: true, force: true }); });
