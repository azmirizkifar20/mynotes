const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
(async () => {
  const source = fs.readFileSync(path.join(__dirname, '../src/frontend/public/js/features/task-board/mention-text.js'), 'utf8');
  const { mentionToken, descriptionParts, descriptionText, descriptionHTML } = await import('data:text/javascript;base64,' + Buffer.from(source).toString('base64'));
  const id = 'aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaaa';
  const name = 'file ] & ü.md', token = mentionToken({ id, path: '/' + name });
  const text = 'Read ' + token + '\nThen ' + token;
  assert.equal(descriptionParts(text).filter((part) => part.id === id).length, 2);
  const docs = [{ id, path: '/moved/new name.md' }];
  assert.equal(descriptionText(text, docs), 'Read @new name.md\nThen @new name.md');
  assert.equal(descriptionText(token, []), '@' + name);
  const escape = (s) => String(s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);
  const html = descriptionHTML('<img src=x>' + token, docs, { escape, appUrl: (p) => '/mynotes' + p });
  assert(html.includes('&lt;img src=x&gt;'));
  assert(html.includes('/mynotes/api/task-board/documents/' + id + '/open'));
  assert(html.includes('target="_blank"') && html.includes('rel="noopener"'));
  assert(!descriptionHTML(token, [], { escape, appUrl: (p) => p }).includes('href='));
  assert(descriptionHTML(token, [], { escape, appUrl: (p) => p }).includes('tidak tersedia'));
  assert.equal(descriptionText('@[bad](doc:javascript:evil)', docs), '@[bad](doc:javascript:evil)');
  assert.doesNotThrow(() => descriptionParts('@[%ZZ](doc:' + id + ')'));
  const render = (text, editing = false) => descriptionHTML(text, docs, { escape, appUrl: (p) => '/mynotes' + p }, editing);
  const url = 'https://docs.google.com/spreadsheets/d/example/edit?gid=1696100077&tab=one#gid=1696100077';
  const linked = render('Dokumen test case:\n' + url, true);
  assert(linked.includes('href="' + escape(url) + '"'), 'Complete external URL keeps query and fragment');
  assert(linked.includes('target="_blank" rel="noopener noreferrer"'), 'External link opens isolated tab');
  assert(linked.includes('contenteditable="false"'), 'Editor link is clickable');
  assert(linked.includes('<br>') && linked.includes('>' + escape(url) + '</a>'), 'Readable URL and newline preserved');
  assert(!linked.includes('/mynotes/https:'), 'External links are not prefixed by app mount');
  assert.equal((render(url + ' ' + token + ' http://example.test/path').match(/<a /g) || []).length, 3, 'URLs coexist with document mentions');
  assert(render('(https://example.test/a_(b)).').includes('href="https://example.test/a_(b)"'), 'Balanced URL parentheses preserved');
  assert(render('https://example.test/a).').endsWith('</a>).'), 'Prose punctuation stays outside link');
  assert(render('HTTPS://example.test/ü?q=<img>').includes('href="HTTPS://example.test/ü?q="'), 'URL boundary excludes HTML');
  assert(!render('javascript:alert(1) data:text/html,x https:// http://[broken').includes('<a '), 'Unsafe schemes and invalid URLs stay text');
  assert(!render('https://example.test/\" onclick=evil><img src=x>').includes('<img'), 'URL and surrounding text are HTML escaped');
  assert.equal(descriptionText(url + '\n' + token, docs), url + '\n@new name.md', 'Search text stays unchanged');
  console.log('Task mentions and HTTP(S) links: safe HTML, editor links, queries/fragments, punctuation, prefixes and plain search text passed.');
})().catch((error) => { console.error(error); process.exitCode = 1; });
