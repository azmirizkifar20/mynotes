module.exports = async function checkWorkspace(base) {
  const $ = id => document.getElementById(id);
  const check = (value, message) => { if (!value) throw Error(message); };
  const wait = () => new Promise(resolve => setTimeout(resolve, 450));
  const click = async selector => { const node = document.querySelector(selector); check(node && !node.disabled, 'Enabled: ' + selector); node.click(); await wait(); };
  const fill = (id, value) => {
    const node = id === 'board-task-description' ? document.querySelector('#board-task-description-editor .vditor-ir [contenteditable]') : $(id);
    if (node.isContentEditable) node.textContent = value; else node.value = value;
    node.dispatchEvent(new Event('input', { bubbles: true }));
  };
  const post = (path, body = {}) => fetch(base + path, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
  const snapshot = () => fetch(base + '/fixture/state').then(response => response.json());
  await click('#board-new-task');
  fill('board-task-name', '<img onerror=evil> Migration task');
  fill('board-task-description', 'Unique migration description https://example.com @[api notes.md](doc:aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaaa)');
  fill('board-task-start', '2026-11-23'); fill('board-task-due', '2026-11-26');
  await click('#board-checklist-add');
  const checklist = document.querySelector('[data-checklist-field=text]'); checklist.value = 'Verify migration'; checklist.dispatchEvent(new Event('input', { bubbles: true }));
  $('board-task-form').requestSubmit(); await wait();
  const created = (await snapshot()).tasks.at(-1);
  check(created.title.includes('<img') && created.checklist.length === 1, 'Create task with checklist');
  check(!document.querySelector('.tb-card img'), 'Vue title escaping');
  check(document.querySelector('[data-board-task="' + created.id + '"] [aria-label="1 dokumen disebut"]'), 'Document mention count');
  fill('board-search', 'unique migration'); check(document.querySelectorAll('.tb-card').length === 1, 'Search description');
  fill('board-search', 'no match'); check(!$('board-empty-search').hidden, 'Empty search'); await click('[data-action=clearBoardSearch]');
  await click('#board-list-tab');
  check(document.querySelectorAll('.tb-list tbody tr').length === 5, 'List view');
  const status = document.querySelector('[data-task-id="' + created.id + '"][data-board-quick=statusId]');
  check(status.hidden && status.parentElement.querySelector('.tb-select-trigger'), 'Existing custom select decoration');
  status.value = (await snapshot()).statuses[2].id; status.dispatchEvent(new Event('change', { bubbles: true })); await wait();
  check((await snapshot()).tasks.at(-1).statusId === status.value, 'Quick status mutation and Vue repaint');
  await click('#board-timeline-tab');
  check(document.querySelectorAll('.tb-timeline-table thead th').length === 8, 'Weekly timeline');
  await click('[data-action=moveBoardWeek][data-arg="1"]'); await click('[data-action=moveBoardWeek][data-arg=today]');
  await click('#board-active-tab');
  await click('.tb-card [data-action=openBoardTask][data-arg="' + created.id + '"]');
  fill('board-task-name', 'Conflict buffer'); await post('/fixture/conflict'); $('board-task-form').requestSubmit(); await wait();
  check($('board-task-dialog').open && !$('board-task-reload').hidden && $('board-task-name').value === 'Conflict buffer', 'Revision conflict preserves text');
  await click('#board-task-reload'); $('board-task-form').requestSubmit(); await wait();
  await click('.tb-card [data-action=openBoardTask][data-arg="' + created.id + '"]');
  fill('board-task-name', 'Retry buffer'); await post('/fixture/fail'); $('board-task-form').requestSubmit(); await wait();
  check($('board-task-dialog').open && $('board-task-error').textContent.includes('unavailable'), 'Failed write preserves input');
  $('board-task-form').requestSubmit(); await wait();
  await click('.tb-card [data-action=openBoardTask][data-arg="' + created.id + '"]');
  const transfer = new DataTransfer(); transfer.items.add(new File(['%PDF-1.7\nfixture'], 'fixture.pdf', { type: 'application/pdf' }));
  $('board-attachments').open = true;
  $('board-attachments').dispatchEvent(new DragEvent('drop', { bubbles: true, cancelable: true, dataTransfer: transfer }));
  check($('board-confirm-dialog').open && !(await snapshot()).tasks.at(-1).attachments?.length, 'Attachment drop requires confirmation');
  document.querySelector('#board-confirm-dialog form').requestSubmit(); await wait();
  check((await snapshot()).tasks.at(-1).attachments?.length === 1 && $('board-attachment-list').textContent.includes('fixture.pdf'), 'Confirmed attachment upload');
  $('board-task-status').value = (await snapshot()).statuses[3].id;
  $('board-task-status').dispatchEvent(new Event('input', { bubbles: true }));
  $('board-task-form').requestSubmit(); await wait();
  await click('.tb-card [data-action=openBoardTask][data-arg="' + created.id + '"]');
  await click('#board-task-archive'); document.querySelector('#board-confirm-dialog form').requestSubmit(); await wait();
  check(!document.querySelector('.tb-card[data-board-task="' + created.id + '"]'), 'Archived task removed from active Vue cards');
  await click('#board-archive-tab');
  check(document.querySelectorAll('.tb-archive-row').length === 1, 'Archive Vue view');
  await click('[data-action=restoreBoardTask][data-arg="' + created.id + '"]');
  check($('board-confirm-dialog').open, 'Restore confirmation'); document.querySelector('#board-confirm-dialog form').requestSubmit(); await wait();
  check(!(await snapshot()).tasks.at(-1).archivedAt, 'Restore archive action');
  await click('#board-active-tab');
  await click('.tb-card [data-action=openBoardTask][data-arg="' + created.id + '"]');
  await click('[data-action=confirmBoardTaskDelete]'); document.querySelector('#board-confirm-dialog form').requestSubmit(); await wait();
  check((await snapshot()).tasks.length === 4, 'Delete task');
  for (const page of ['today', 'home', 'sticky', 'recent', 'passkeys', 'templates', 'activity', 'trash']) {
    const link = document.querySelector('[data-nav="' + page + '"]') || document.querySelector('[data-action=navigate][data-arg="' + page + '"]');
    check(link, 'Navigation ' + page); link.click(); await wait(); check(!document.querySelector('.task-board'), 'Vue unmounted for ' + page);
  }
  await click('[data-nav=tasks]'); check(document.querySelectorAll('.tb-column').length === 4, 'Return to board');
  await click('[data-action=navigate][data-arg=home]'); await post('/fixture/fail'); await click('[data-nav=tasks]');
  check(!$('board-retry').hidden, 'Initial read failure'); await click('#board-retry');
  check(document.querySelectorAll('.tb-column').length === 4, 'Retry remounts Vue');
  return 'Task CRUD, checklist, mentions, confirmed attachment drop, archive/restore, search, quick edit, weekly timeline, conflicts, retry and navigation passed';
};
